import pytest

from src.widget import get_date, mask_account, mask_account_card


@pytest.mark.parametrize(
    "number_card, expected",
    [
        # Стандартный формат ввода
        ("Maestro 1596837868705199", "Maestro 1596 83** **** 5199"),
        # Введет номер счета
        ("Счет 64686473678894779589", "Вы ввели номер счёта, а не номер карты"),
        # Ввод со склеенным названием карты
        ("MasterCard 7158300734726758", "MasterCard 7158 30** **** 6758"),
        # Введен номер счета
        ("Счет 35383033474447895560", "Вы ввели номер счёта, а не номер карты"),
        # Ввод названия карты, состоящего из 2 и более слов
        ("Visa Classic 6831982476737658", "Visa Classic 6831 98** **** 7658"),
        # В номере карты не соответствует количество цифр
        ("Visa Platinum 899092213665224", "Введены некорректные данные, номер карты должен содержать 16 цифр"),
        # В номере карты не соответствует количество цифр
        ("Visa Gold 599941422842635354", "Введены некорректные данные, номер карты должен содержать 16 цифр"),
        # Введен номер счета
        ("Счет 73654108430135874305", "Вы ввели номер счёта, а не номер карты"),
    ],
)
def test_mask_account_card(number_card: str, expected: str) -> None:
    assert mask_account_card(number_card) == expected


@pytest.mark.parametrize(
    "number_account, expected",
    [
        # Введен номер карты
        ("Maestro 1596837868705199", "Вы ввели номер карты, а не номер счета"),
        # Стандартный формат ввода
        ("Счет 64686473678894779589", "Счет **9589"),
        # Введен номер карты
        ("MasterCard 7158300734726758", "Вы ввели номер карты, а не номер счета"),
        # В номере счета присутствуют лишние символы
        ("Счет 353830334H4447895560", "Номер счета должен содержать только цифры"),
        # Введен номер карты
        ("Visa Classic 6831982476737658", "Вы ввели номер карты, а не номер счета"),
        # Введен номер карты
        ("Visa Platinum 8990922113665229", "Вы ввели номер карты, а не номер счета"),
        # Введен номер карты
        ("Visa Gold 5999414228426353", "Вы ввели номер карты, а не номер счета"),
        # В номере счета несоответствует количество цифр
        ("Счет 73654105874305", "Введены некорректные данные, номер счета должен содержать 20 цифр"),
    ],
)
def test_mask_account(number_account: str, expected: str) -> None:
    assert mask_account(number_account) == expected


@pytest.mark.parametrize(
    "date_string, expected",
    [
        # Стандартный формат ISO с временем
        ("2024-03-15T10:30:00", "15.03.2024"),
        # Формат ISO только с датой
        ("2023-12-01", "01.12.2023"),
        # Граничный случай: начало года
        ("2022-01-01T00:00:00", "01.01.2022"),
        # Граничный случай: конец года
        ("2021-12-31T23:59:59", "31.12.2021"),
        # Високосный год
        ("2024-02-29T12:00:00", "29.02.2024"),
    ],
)
def test_get_date_success(date_string: str, expected: str) -> None:
    assert get_date(date_string) == expected


@pytest.mark.parametrize(
    "invalid_date_string",
    [
        "не дата",
        "2024/03/15",  # Неверный разделитель
        "15-03-2024",  # Неверный порядок
        "2024-13-01",  # Несуществующий месяц
        "2024-02-30",  # Несуществующий день
        "",  # Пустая строка
    ],
)
def test_get_date_invalid(invalid_date_string: str) -> None:
    with pytest.raises(ValueError):
        get_date(invalid_date_string)
